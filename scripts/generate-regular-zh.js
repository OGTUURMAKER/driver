#!/usr/bin/env node
/**
 * Builds public/data/questions.zh.json (the Chinese display layer shown under
 * each 40-chapter question image) from the reviewable source:
 *
 *   data-source/regular-zh/chapter-NN.json
 *     { "chapter-01-q01": { "mn": { question, options[] },   ← transcribed from the image
 *                           "zh": { question, options[] },   ← translation shown to students
 *                           "note"?: "…" } }
 *
 * The Mongolian transcription stays in data-source for reviewers; only the
 * Chinese text is published. No answers are read from or written to these
 * files — scoring always uses public/data/questions.json.
 *
 * Usage: node scripts/generate-regular-zh.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SOURCE_DIR = path.join(ROOT, "data-source", "regular-zh");
const BANK = path.join(ROOT, "public", "data", "questions.json");
const OUT = path.join(ROOT, "public", "data", "questions.zh.json");

function main() {
  const bank = JSON.parse(fs.readFileSync(BANK, "utf8"));
  const ids = new Set(bank.map((q) => q.id));
  const questions = {};
  const problems = [];

  const files = fs.existsSync(SOURCE_DIR)
    ? fs.readdirSync(SOURCE_DIR).filter((f) => /^chapter-\d{2}\.json$/.test(f)).sort()
    : [];

  for (const file of files) {
    const entries = JSON.parse(fs.readFileSync(path.join(SOURCE_DIR, file), "utf8"));
    for (const [id, entry] of Object.entries(entries)) {
      if (!ids.has(id)) {
        problems.push(`${file}: unknown question id ${id}`);
        continue;
      }
      const zh = entry && entry.zh;
      if (!zh || typeof zh.question !== "string" || !Array.isArray(zh.options)) {
        problems.push(`${id}: missing zh.question / zh.options`);
        continue;
      }
      questions[id] = { question: zh.question, options: zh.options.slice() };
    }
  }

  // Keep the bank's order so diffs stay readable.
  const ordered = {};
  for (const q of bank) if (questions[q.id]) ordered[q.id] = questions[q.id];

  const doc = {
    _about:
      "Simplified Chinese display layer for the 40-chapter bank (public/data/questions.json). " +
      "Generated by scripts/generate-regular-zh.js from data-source/regular-zh/ — edit the source, not this file. " +
      "Options are in the same order as the numbered choices printed on each image; no answers are stored here.",
    language: "zh-CN",
    questions: ordered
  };
  fs.writeFileSync(OUT, JSON.stringify(doc, null, 2) + "\n");

  console.log(`Wrote ${path.relative(ROOT, OUT)}: ${Object.keys(ordered).length} / ${bank.length} questions`);
  if (problems.length) {
    console.error(problems.map((p) => "  ✗ " + p).join("\n"));
    process.exit(1);
  }
}

main();
